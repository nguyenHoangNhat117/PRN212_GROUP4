"""Generate standalone demo and empty-production installers from the tested base."""
from pathlib import Path
root=Path(__file__).resolve().parents[1]
base=(root/'Database/StudentManagement_G4.sql').read_text()
seed=(root/'Database/Seeds/FullProject_Demo.sql').read_text()
def dynamic(body):
 return "\nDECLARE @PackageSql nvarchar(max)=N'USE '+QUOTENAME(@DatabaseName)+N';\n"+body.replace("'","''")+"';\nEXEC sys.sp_executesql @PackageSql;\n"
# Only this dedicated installer opts a NEW database into demo seeding.
demo=base.replace("@DatabaseName sysname=N'PRN212_StudentManagement_G4'","@DatabaseName sysname=N'PRN212_StudentManagement_G4_Demo'")
demo+=dynamic("EXEC sys.sp_addextendedproperty @name=N'G4.DemoSeedAllowed',@value=N'1';\n"+seed)
(root/'Database/Install_FullProject_Demo.sql').write_text('-- GENERATED by scripts/Build-DatabasePackages.py. Demo database only.\n'+demo)
# Keep roles/permissions and the explicit, reviewable grade-policy template only.
prod=base
start=prod.index('INSERT dbo.Departments(')
grade_start=prod.index('INSERT dbo.GradeScale(',start)
grade_end=prod.index('/* Users have distinct',grade_start)
end=prod.index("\n'';\nEXEC sys.sp_executesql N''/* Only finalized",grade_end)
prod=prod[:start]+prod[grade_start:grade_end]+prod[end:]
import re
prod=re.sub(r" IF \(SELECT COUNT\(\*\) FROM dbo\.(CourseEnrollments|Enrollments|Grades)\)<>\d+ THROW 5140[123],''Unexpected[^\n]+\n",'',prod)
prod=prod.replace("@DatabaseName sysname=N'PRN212_StudentManagement_G4'","@DatabaseName sysname=N'PRN212_StudentManagement_G4_Production'")
needle='IF @@TRANCOUNT<>0'
prod=prod.replace(needle,"""-- Set to 1 ONLY after the team approves the GradeScale template below,
-- or edit its INSERT values to the approved policy first. No sample accounts/data.
DECLARE @GradePolicyConfirmed bit=0;
IF @GradePolicyConfirmed<>1 THROW 51610,'Review GradeScale and set GradePolicyConfirmed=1 before production install.',1;
"""+needle,1)
# Replace stale demo header in generated production file.
prod=prod[prod.index('SET QUOTED_IDENTIFIER ON;'):]
(root/'Database/Install_Production.sql').write_text('-- GENERATED by scripts/Build-DatabasePackages.py. NEW database only.\n-- Empty business tables; roles/permissions and approved grade scale only.\n'+prod)
